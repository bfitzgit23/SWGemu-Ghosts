local function isKeeper(name)
	for i = 1, #KEEP_PREFIXES do
		local prefix = KEEP_PREFIXES[i]
		if string.sub(name, 1, #prefix) == prefix then
			return true
		end
	end
	return false
end

local function surrenderAll(creature)
	local removed = 0
	for pass = 1, MAX_PASSES do
		local changed = 0
		for i = 1, #SKILLS do
			local name = SKILLS[i]
			if creature:hasSkill(name) then
				creature:surrenderSkill(name)
				if not creature:hasSkill(name) then
					changed = changed + 1
				end
			end
		end
		removed = removed + changed
		if changed == 0 then
			break
		end
	end
	return removed
end

function ResetBennjiJedi:playerLoggedIn(pPlayer)
	if pPlayer == nil then return end

	local creature = CreatureObject(pPlayer)
	local firstName = string.lower(creature:getFirstName() or "")

	if not TARGET_NAMES[firstName] then return end

	local ghost = creature:getPlayerObject()
	if ghost == nil then return end
	if PlayerObject(ghost):getAccountID() ~= TARGET_ACCOUNT_ID then return end
	if readScreenPlayData(pPlayer, "ResetBennjiJedi", "done") == "1" then return end

	creature:sendSystemMessage("\\#FFAA00[Bennji Reset]\\#FFFFFF Resetting skills, keeping Force Sensitive and Jedi progression...")

	-- Let the Jedi manager accept every surrender for this one pass.
	writeScreenPlayData(pPlayer, "ResetBennjiJedi", "allow", "1")

	local removed = surrenderAll(creature)

	local left = 0
	local firstLeft = ""
	for i = 1, #SKILLS do
		local name = SKILLS[i]
		if creature:hasSkill(name) then
			left = left + 1
			if firstLeft == "" then firstLeft = name end
		end
	end

	writeScreenPlayData(pPlayer, "ResetBennjiJedi", "allow", "0")

	print("ResetBennjiJedi: " .. creature:getFirstName() .. " surrendered " .. removed .. " skills, leftovers " .. left .. (firstLeft ~= "" and (" first=" .. firstLeft) or ""))

	if left == 0 then
		creature:sendSystemMessage("\\#FFAA00[Bennji Reset]\\#FFFFFF Done. " .. removed .. " skills removed; Force Sensitive and Jedi progression kept.")
		writeScreenPlayData(pPlayer, "ResetBennjiJedi", "done", "1")
	else
		creature:sendSystemMessage("\\#FFAA00[Bennji Reset]\\#FFFFFF Removed " .. removed .. " skills, but " .. left .. " could not be removed (first: " .. firstLeft .. "). Check the server log.")
	end
end
